import { CODE_MINUTES } from './auth-options.ts'
import type { Bindings } from './env.ts'

/** Sends the sign-in code through Resend. Throws on any non-2xx answer. */
export async function sendLoginEmail(env: Pick<Bindings, 'MAIL_FROM' | 'RESEND_API_KEY'>, to: string, code: string) {
  // The code leads the subject so it shows in notification previews
  const subject = `${code} is your Worship Hub sign-in code`
  const text = [
    `Your Worship Hub sign-in code is ${code}`,
    '',
    `It works once and expires in ${CODE_MINUTES} minutes.`,
    "If you didn't ask for it, you can ignore this email.",
  ].join('\n')
  // `code` is digits only (generated by Better Auth), so it needs no HTML escaping
  const html = `<!doctype html>
<html lang="en">
  <body style="margin:0;padding:24px;background:#f8fafc;font-family:-apple-system,Segoe UI,Roboto,sans-serif;color:#0f172a">
    <div style="max-width:420px;margin:0 auto;background:#ffffff;border-radius:12px;padding:24px">
      <h1 style="margin:0 0 12px;font-size:18px">Worship Hub</h1>
      <p style="margin:0 0 20px;line-height:1.5">Enter this code to sign in. It works once and expires in ${CODE_MINUTES} minutes.</p>
      <p style="margin:0 0 20px;font-size:32px;font-weight:700;letter-spacing:8px;font-family:ui-monospace,Menlo,Consolas,monospace">${code}</p>
      <p style="margin:0;font-size:13px;color:#64748b">If you didn't ask for this email, you can ignore it.</p>
    </div>
  </body>
</html>`

  const response = await fetch('https://api.resend.com/emails', {
    method: 'POST',
    headers: { Authorization: `Bearer ${env.RESEND_API_KEY}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ from: env.MAIL_FROM, to: [to], subject, text, html }),
  })
  if (!response.ok) {
    // Resend explains failures in a JSON body; never log the address or the code
    const detail = await response
      .json()
      .then((body) => (body as { message?: string }).message ?? '')
      .catch(() => '')
    throw new Error(`Resend responded ${response.status}${detail ? `: ${detail}` : ''}`)
  }
}
